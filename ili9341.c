#include "stm32f429_regs.h"

static void delay_ms(volatile uint32_t ms) {
    while (ms--) {
        volatile uint32_t count = 56000;
        while (count--) { __asm__("nop"); }
    }
}

static void ili9341_write_cmd(uint8_t cmd) {
    spi5_cs_low();
    spi5_dc_cmd();
    spi5_write(cmd);
    spi5_cs_high();
}

static void ili9341_write_data(uint8_t data) {
    spi5_cs_low();
    spi5_dc_data();
    spi5_write(data);
    spi5_cs_high();
}

void ili9341_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1) {
    ili9341_write_cmd(0x2A);
    ili9341_write_data(x0 >> 8);
    ili9341_write_data(x0 & 0xFF);
    ili9341_write_data(x1 >> 8);
    ili9341_write_data(x1 & 0xFF);

    ili9341_write_cmd(0x2B);
    ili9341_write_data(y0 >> 8);
    ili9341_write_data(y0 & 0xFF);
    ili9341_write_data(y1 >> 8);
    ili9341_write_data(y1 & 0xFF);

    ili9341_write_cmd(0x2C);
}

void ili9341_fill_screen(uint16_t color) {
    ili9341_set_window(0, 0, ILI9341_WIDTH - 1, ILI9341_HEIGHT - 1);
    
    spi5_cs_low();
    spi5_dc_data();
    uint8_t hi = color >> 8;
    uint8_t lo = color & 0xFF;
    for (uint32_t i = 0; i < (uint32_t)ILI9341_WIDTH * ILI9341_HEIGHT; i++) {
        spi5_write(hi);
        spi5_write(lo);
    }
    spi5_cs_high();
}

void ili9341_fill_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color) {
    if ((x >= ILI9341_WIDTH) || (y >= ILI9341_HEIGHT)) return;
    if ((x + w - 1) >= ILI9341_WIDTH)  w = ILI9341_WIDTH  - x;
    if ((y + h - 1) >= ILI9341_HEIGHT) h = ILI9341_HEIGHT - y;

    ili9341_set_window(x, y, x + w - 1, y + h - 1);

    spi5_cs_low();
    spi5_dc_data();
    uint8_t hi = color >> 8;
    uint8_t lo = color & 0xFF;
    for (uint32_t i = 0; i < (uint32_t)w * h; i++) {
        spi5_write(hi);
        spi5_write(lo);
    }
    spi5_cs_high();
}

void ili9341_draw_pixel(uint16_t x, uint16_t y, uint16_t color) {
    if (x >= ILI9341_WIDTH || y >= ILI9341_HEIGHT) return;
    ili9341_set_window(x, y, x, y);
    spi5_cs_low();
    spi5_dc_data();
    spi5_write(color >> 8);
    spi5_write(color & 0xFF);
    spi5_cs_high();
}

