void ili9341_draw_char(uint16_t x, uint16_t y, char c, uint16_t color, uint16_t bg) {
    if (x + 8 > ILI9341_WIDTH || y + 16 > ILI9341_HEIGHT) return;
    const uint8_t *bitmap = font8x16_basic[(uint8_t)c];
    
    ili9341_set_window(x, y, x + 7, y + 15);
    spi5_cs_low();
    spi5_dc_data();

    uint8_t hi_col = color >> 8, lo_col = color & 0xFF;
    uint8_t hi_bg  = bg >> 8,    lo_bg  = bg & 0xFF;

    for (int row = 0; row < 16; row++) {
        uint8_t line = bitmap[row];
        for (int col = 0; col < 8; col++) {
            if (line & (0x80 >> col)) {
                spi5_write(hi_col);
                spi5_write(lo_col);
            } else {
                spi5_write(hi_bg);
                spi5_write(lo_bg);
            }
        }
    }
    spi5_cs_high();
}

void ili9341_draw_string(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg) {
    while (*str) {
        ili9341_draw_char(x, y, *str++, color, bg);
        x += 8;
        if (x + 8 > ILI9341_WIDTH) break;
    }
}

